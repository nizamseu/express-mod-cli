const { CONFIG_FILE, DB_TYPES } = require("./projectConfig");

const languageLabel = (language) =>
  language === "ts" ? "TypeScript" : "JavaScript";

const dbList = Object.keys(DB_TYPES).join(", ");

/** One line per field: "  price    number, optional" */
const describeFields = (fields) => {
  const width = Math.max(...fields.map((field) => field.name.length));

  return fields
    .map((field) => {
      const type = field.type === "enum" ? `enum (${field.values.join(", ")})` : field.type;
      const notes = [
        field.required ? "required" : field.optional ? "optional" : null,
        field.unique ? "unique" : null,
        field.hasDefault ? `default ${JSON.stringify(field.default)}` : null,
      ].filter(Boolean);
      return `  ${field.name.padEnd(width)}  ${type}, ${notes.join(", ")}`;
    })
    .join("\n");
};

